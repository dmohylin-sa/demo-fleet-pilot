// Field labels: keys like "pallets_2" map to "field.pallets_n" with n = 2.
export function fieldLabel(t, key) {
  const m = key.match(/^(.*)_(\d+)$/);
  return m ? t(`field.${m[1]}_n`, { n: m[2] }) : t(`field.${key}`);
}
